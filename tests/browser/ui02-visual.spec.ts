import { advanced } from './helpers/authoring';
import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const directory = join(tmpdir(), 'cadesimu-ui02');
test.beforeAll(async () => { await mkdir(directory, { recursive: true }); });

for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }]) test(`actual A shell/context/fit comparison ${viewport.width}`, async ({ page }) => {
  await page.setViewportSize(viewport); await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Select a symbol', exact: true })).toBeVisible();
  await expect(page.getByLabel('Cursor X', { exact: true })).toBeHidden();
  await expect(page.getByRole('combobox', { name: 'Wire from', exact: true })).toBeHidden();
  await expect(page.getByRole('button', { name: 'Pan left', exact: true })).toBeHidden();
  await expect(page.getByRole('button', { name: 'Inspect project JSON', exact: true })).toBeHidden();
  expect(await page.locator('.palette button svg').count()).toBe(7);
  await page.screenshot({ path: join(directory, `actual-${viewport.width}-blank.png`) });
  await advanced(page); await expect(page.getByLabel('Cursor X', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pan left', exact: true })).toBeVisible();
  await page.getByText('Advanced workspace', { exact: true }).click();
  await page.locator('.file-feedback > summary').click();
  await page.getByText('More files', { exact: true }).click();
  await expect(page.locator('.file-feedback')).not.toHaveAttribute('open');
  page.once('dialog', d => d.accept('Discard')); await page.getByRole('button', { name: 'Load example', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Objects (7 symbols)' })).toBeVisible();
  const canvas = page.getByRole('img', { name: 'Circuit drawing canvas' });
  const coil = page.locator('[data-instance="instance_coil"] .design-glyph rect');
  const lamp = page.locator('[data-instance="instance_lamp"] .design-glyph circle');
  expect((await coil.boundingBox())!.width).toBeGreaterThanOrEqual(24);
  expect((await lamp.boundingBox())!.width).toBeGreaterThanOrEqual(24);
  const name = page.locator('[data-marking="name"]').filter({ hasText: 'K1' }).first();
  const pixels = await name.evaluate(el => { const m = (el as SVGGraphicsElement).getScreenCTM()!; return Number.parseFloat(getComputedStyle(el).fontSize) * Math.hypot(m.a, m.b); });
  expect(pixels).toBeGreaterThanOrEqual(11);
  const board = (await canvas.boundingBox())!, left = (await page.getByRole('complementary', { name: 'Palette and objects' }).boundingBox())!, right = (await page.getByRole('complementary', { name: 'Inspector and wiring' }).boundingBox())!;
  expect(left.x + left.width).toBeLessThanOrEqual(board.x + 1); expect(board.x + board.width).toBeLessThanOrEqual(right.x + 1);
  expect(right.x + right.width).toBeLessThanOrEqual(viewport.width); expect(board.height).toBeGreaterThan(450);
  await page.locator('[data-instance="instance_hold"] > rect').first().click();
  await expect(page.getByRole('heading', { name: 'Select a symbol', exact: true })).toHaveCount(0);
  await expect(page.getByRole('combobox', { name: 'Bound device', exact: true })).toHaveValue('device_relay');
  await expect(page.getByRole('button', { name: 'Apply binding', exact: true })).toBeVisible();
  await expect(page.getByRole('combobox', { name: 'Wire from', exact: true })).toBeHidden();
  await page.screenshot({ path: join(directory, `actual-${viewport.width}-binding.png`) });
  await page.getByRole('button', { name: 'Run', exact: true }).click();
  await expect(page.locator('[data-observable="device_relay/energized"]')).toContainText('false');
  const start = page.locator('[data-instance="instance_start"]'); await start.focus(); await page.keyboard.down(' ');
  await expect(page.locator('[data-observable="device_relay/energized"]')).toContainText('true'); await page.keyboard.up(' ');
  await expect(page.locator('[data-instance="instance_lamp"] [data-lit-rays]')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Stop simulation', exact: true })).toBeInViewport();
  expect(await page.locator('.simulation').evaluate(el => getComputedStyle(el).position)).toBe('static');
  await page.screenshot({ path: join(directory, `actual-${viewport.width}-run.png`) });
});
